"""Versioned PostgreSQL schema for the coordinator (decision 0008).

Each migration runs once, in order, inside one transaction, behind an
advisory lock, so two coordinator processes that start together cannot both
apply it. Never edit an applied migration. Add a new one.
"""

import time

MIGRATION_LOCK = 0x1E_5C_4E_0A  # pg_advisory_xact_lock key for schema changes

