MIGRATIONS: list[tuple[int, str, str]] = [
    (1, "baseline from the SQLite store", BASELINE),
]

# Tables in foreign-key order, for copies and checks.
TABLES = (
    "accounts", "users", "provider_nodes", "api_keys", "provider_tokens",
    "transactions", "provider_history", "provider_ownership_actions",
    "reference_prices", "account_actions", "request_outcomes",
)


def migrate(conn) -> list[int]:
    """Apply pending migrations. Returns the versions applied by this call."""
    applied = []
    with conn:
        conn.execute("SELECT pg_advisory_xact_lock(?)", (MIGRATION_LOCK,))
        conn.execute(
            "CREATE TABLE IF NOT EXISTS schema_migrations ("
            "version INTEGER PRIMARY KEY, name TEXT NOT NULL, applied_at DOUBLE PRECISION NOT NULL)"
        )
        done = {row[0] for row in conn.execute("SELECT version FROM schema_migrations")}
        for version, name, sql in MIGRATIONS:
            if version in done:
                continue
            conn.execute(sql)
            conn.execute(
                "INSERT INTO schema_migrations (version, name, applied_at) VALUES (?, ?, ?)",
                (version, name, time.time()),
            )
            applied.append(version)
    return applied
